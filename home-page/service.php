    <script>
        (function() {
            function initMdsServices() {
                var section = document.getElementById("mds-services");

                if (!section || section.dataset.mdsReady === "true") {
                    return;
                }

                section.dataset.mdsReady = "true";

                var sectionVisible = false;
                var cardsTimer = null;

                function clearTimers() {
                    if (cardsTimer) {
                        window.clearTimeout(cardsTimer);
                        cardsTimer = null;
                    }
                }

                function hideSection() {
                    clearTimers();
                    section.classList.remove("mds-section-visible");
                    section.classList.remove("mds-cards-ready");
                }

                function scheduleCards() {
                    cardsTimer = window.setTimeout(function() {
                        if (sectionVisible) {
                            section.classList.add("mds-cards-ready");
                        }
                    }, 500);
                }

                function showSection() {
                    clearTimers();

                    section.classList.remove("mds-section-visible");
                    section.classList.remove("mds-cards-ready");

                    void section.offsetWidth;

                    section.classList.add("mds-section-visible");
                    scheduleCards();
                }

                if (!("IntersectionObserver" in window)) {
                    sectionVisible = true;
                    showSection();
                    return;
                }

                var observer = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            var isVisible =
                                entry.isIntersecting &&
                                entry.intersectionRatio >= 0.16;

                            if (isVisible && !sectionVisible) {
                                sectionVisible = true;
                                showSection();
                            }

                            if (!isVisible && sectionVisible) {
                                sectionVisible = false;
                                hideSection();
                            }
                        });
                    }, {
                        threshold: [0, 0.16, 0.35, 0.6],
                        rootMargin: "0px 0px -25px 0px"
                    }
                );

                observer.observe(section);
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMdsServices
                );
            } else {
                initMdsServices();
            }

            window.addEventListener(
                "elementor/frontend/init",
                function() {
                    window.setTimeout(initMdsServices, 250);
                }
            );
        })();
    </script>
