    <script>
        (function() {
            function initMwcSection() {
                var section = document.getElementById("mwcWhyChoose");

                if (!section || section.getAttribute("data-mwc-ready") === "true") {
                    return;
                }

                section.setAttribute("data-mwc-ready", "true");

                var items = section.querySelectorAll(".mwc-reveal");

                if (!("IntersectionObserver" in window)) {
                    items.forEach(function(item) {
                        item.classList.add("mwc-visible");
                    });

                    return;
                }

                var observer = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            entry.target.classList.toggle(
                                "mwc-visible",
                                entry.isIntersecting
                            );
                        });
                    }, {
                        threshold: 0.12,
                        rootMargin: "0px 0px -30px 0px"
                    }
                );

                items.forEach(function(item) {
                    observer.observe(item);
                });
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMwcSection
                );
            } else {
                initMwcSection();
            }

            window.addEventListener("elementor/frontend/init", function() {
                setTimeout(initMwcSection, 250);
            });
        })();
    </script>

