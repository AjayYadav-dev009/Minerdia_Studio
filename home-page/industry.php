    <script>
        (function() {
            function initMniIndustries() {
                var section = document.getElementById("mni-industries-section");

                if (!section || section.getAttribute("data-mni-ready") === "true") {
                    return;
                }

                section.setAttribute("data-mni-ready", "true");

                /* Clone cards once for seamless slider */
                var track = section.querySelector(".mni-track");

                if (track && track.getAttribute("data-mni-cloned") !== "true") {
                    var cards = Array.prototype.slice.call(track.children);

                    cards.forEach(function(card) {
                        var clone = card.cloneNode(true);
                        clone.setAttribute("aria-hidden", "true");
                        track.appendChild(clone);
                    });

                    track.setAttribute("data-mni-cloned", "true");
                }

                /* Repeating Scroll Reveal */
                var revealItems = section.querySelectorAll(".mni-reveal");

                if (!("IntersectionObserver" in window)) {
                    revealItems.forEach(function(item) {
                        item.classList.add("mni-visible");
                    });
                    return;
                }

                var observer = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            entry.target.classList.toggle(
                                "mni-visible",
                                entry.isIntersecting
                            );
                        });
                    }, {
                        threshold: 0.12,
                        rootMargin: "0px 0px -30px 0px"
                    }
                );

                revealItems.forEach(function(item) {
                    observer.observe(item);
                });
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMniIndustries
                );
            } else {
                initMniIndustries();
            }

            window.addEventListener("elementor/frontend/init", function() {
                setTimeout(initMniIndustries, 250);
            });
        })();
    </script>

