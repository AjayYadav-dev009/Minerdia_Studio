    <script>
        (function() {
            function initMvgjSection() {
                var section = document.getElementById("mvgjGrowthJourney");

                if (
                    !section ||
                    section.getAttribute("data-mvgj-ready") === "true"
                ) {
                    return;
                }

                section.setAttribute("data-mvgj-ready", "true");

                var headerItems = section.querySelectorAll(
                    ".mvgj-header-reveal"
                );

                var timeline = section.querySelector(".mvgj-timeline");
                var items = section.querySelectorAll(".mvgj-item");

                if (!("IntersectionObserver" in window)) {
                    headerItems.forEach(function(item) {
                        item.classList.add("mvgj-header-visible");
                    });

                    if (timeline) {
                        timeline.classList.add("mvgj-line-active");
                    }

                    items.forEach(function(item) {
                        item.classList.add("mvgj-item-visible");
                    });

                    return;
                }

                var headerObserver = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            entry.target.classList.toggle(
                                "mvgj-header-visible",
                                entry.isIntersecting
                            );
                        });
                    }, {
                        threshold: 0.14,
                        rootMargin: "0px 0px -25px 0px"
                    }
                );

                headerItems.forEach(function(item) {
                    headerObserver.observe(item);
                });

                if (timeline) {
                    var lineObserver = new IntersectionObserver(
                        function(entries) {
                            entries.forEach(function(entry) {
                                entry.target.classList.toggle(
                                    "mvgj-line-active",
                                    entry.isIntersecting
                                );
                            });
                        }, {
                            threshold: 0.08,
                            rootMargin: "0px 0px -60px 0px"
                        }
                    );

                    lineObserver.observe(timeline);
                }

                var itemObserver = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            entry.target.classList.toggle(
                                "mvgj-item-visible",
                                entry.isIntersecting
                            );
                        });
                    }, {
                        threshold: 0.27,
                        rootMargin: "0px 0px -45px 0px"
                    }
                );

                items.forEach(function(item) {
                    itemObserver.observe(item);
                });
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMvgjSection
                );
            } else {
                initMvgjSection();
            }

            window.addEventListener(
                "elementor/frontend/init",
                function() {
                    setTimeout(initMvgjSection, 250);
                }
            );
        })();
    </script>

