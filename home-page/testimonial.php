    <script>
        (function() {
            function initMgrReviews() {
                var section = document.getElementById("mgrReviewsSection");

                if (
                    !section ||
                    section.getAttribute("data-mgr-ready") === "true"
                ) {
                    return;
                }

                section.setAttribute("data-mgr-ready", "true");

                var track = section.querySelector(".mgr-track");

                if (!track) {
                    return;
                }

                /*
                 * Duplicate every original card once.
                 * This creates a perfectly seamless continuous loop.
                 */
                var originalCards = Array.prototype.slice.call(
                    track.querySelectorAll(".mgr-card")
                );

                originalCards.forEach(function(card) {
                    var clone = card.cloneNode(true);

                    clone.setAttribute("aria-hidden", "true");

                    var cloneImage = clone.querySelector("img");

                    if (cloneImage) {
                        cloneImage.removeAttribute("loading");
                        cloneImage.setAttribute("alt", "");
                    }

                    track.appendChild(clone);
                });

                /*
                 * Scroll reveal animation.
                 */
                var revealItems = section.querySelectorAll(".mgr-reveal");

                if (!("IntersectionObserver" in window)) {
                    revealItems.forEach(function(item) {
                        item.classList.add("mgr-visible");
                    });

                    return;
                }

                var observer = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            entry.target.classList.toggle(
                                "mgr-visible",
                                entry.isIntersecting
                            );
                        });
                    }, {
                        threshold: 0.12,
                        rootMargin: "0px 0px -25px 0px"
                    }
                );

                revealItems.forEach(function(item) {
                    observer.observe(item);
                });
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMgrReviews
                );
            } else {
                initMgrReviews();
            }

            window.addEventListener(
                "elementor/frontend/init",
                function() {
                    setTimeout(initMgrReviews, 250);
                }
            );
        })();
    </script>

