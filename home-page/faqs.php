    <script>
        (function() {
            function initMfqFaq() {
                var section = document.getElementById("mfqFaqSection");

                if (
                    !section ||
                    section.getAttribute("data-mfq-ready") === "true"
                ) {
                    return;
                }

                section.setAttribute("data-mfq-ready", "true");

                /*
                 * Accordion: one answer open at a time.
                 * To allow several open together, delete the
                 * items.forEach(...) line inside the click handler.
                 */
                var items = section.querySelectorAll(".mfq-item");

                function setOpen(item, open) {
                    item.classList.toggle("mfq-open", open);
                    item.querySelector(".mfq-btn").setAttribute(
                        "aria-expanded",
                        String(open)
                    );
                }

                items.forEach(function(item) {
                    item.querySelector(".mfq-btn").addEventListener(
                        "click",
                        function() {
                            var willOpen = !item.classList.contains("mfq-open");

                            items.forEach(function(other) {
                                setOpen(other, false);
                            });

                            setOpen(item, willOpen);
                        }
                    );
                });

                /*
                 * Scroll reveal animation.
                 */
                var revealItems = section.querySelectorAll(".mfq-reveal");

                if (!("IntersectionObserver" in window)) {
                    revealItems.forEach(function(item) {
                        item.classList.add("mfq-visible");
                    });

                    return;
                }

                var observer = new IntersectionObserver(
                    function(entries) {
                        entries.forEach(function(entry) {
                            if (entry.isIntersecting) {
                                entry.target.classList.add("mfq-visible");
                                observer.unobserve(entry.target);
                            }
                        });
                    }, {
                        threshold: 0.12,
                        rootMargin: "0px 0px -25px 0px"
                    }
                );

                revealItems.forEach(function(item) {
                    observer.observe(item);
                });
            }

            if (document.readyState === "loading") {
                document.addEventListener(
                    "DOMContentLoaded",
                    initMfqFaq
                );
            } else {
                initMfqFaq();
            }

            window.addEventListener(
                "elementor/frontend/init",
                function() {
                    setTimeout(initMfqFaq, 250);
                }
            );
        })();
    </script>

